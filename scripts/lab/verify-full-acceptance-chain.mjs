function runCommand(cmd, args, logPath) {
  const result = spawnSync(cmd, args, {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  const output = `$ ${cmd} ${args.join(" ")}\n${result.stdout ?? ""}\n${result.stderr ?? ""}\n`;
  atomicWriteFile(logPath, output, { mode: 0o600 });
  return { status: result.status, output };
}

export async function verifyFullAcceptanceChain() {
  mkdirSync(RUN_DIR, { recursive: true });
  const results = [];
  let overallPass = true;

  log("\n=== establishing full desired state (one-time full reset) ===");
  try {
    fullResetAndEstablishDesiredState();
  } catch (error) {
    logError(`initial full reset failed: ${error.message}`);
    const summary = {
      schemaVersion: 1,
      generatedAt: new Date().toISOString(),
      pass: false,
      gates: [
        { id: "initial-reset", label: "Initial full reset", pass: false, error: error.message },
      ],
    };
    atomicWriteFile(join(RUN_DIR, "summary.json"), `${JSON.stringify(summary, null, 2)}\n`, {
      mode: 0o600,
    });
    return { pass: false, results: summary.gates, summaryPath: join(RUN_DIR, "summary.json") };
  }

  for (const gate of GATES) {
    log(`\n=== gate: ${gate.label} (${gate.id}) ===`);
    if (gate.reset === "queue") {
      log(`--- purging RabbitMQ queues before ${gate.id} (lightweight reset) ---`);
      try {
        queueOnlyReset();
      } catch (error) {
        overallPass = false;
        results.push({
          id: gate.id,
          label: gate.label,
          pass: false,
          error: `queue reset failed: ${error.message}`,
        });
        continue;
      }
    }
    let gatePass = true;
    const commandResults = [];
    for (const [index, [cmd, args]] of gate.commands.entries()) {
      const logPath = join(RUN_DIR, `${gate.id}-${index}.log`);
      const { status, output } = runCommand(cmd, args, logPath);
      const pass = status === 0;
      if (!pass) gatePass = false;
      commandResults.push({ command: `${cmd} ${args.join(" ")}`, pass, exitCode: status, logPath });
      log(`  ${pass ? "PASS" : "FAIL"}: ${cmd} ${args.join(" ")} (log: ${logPath})`);
      if (!pass) log(output.split("\n").slice(-40).join("\n"));
    }
    if (!gatePass) overallPass = false;
    results.push({ id: gate.id, label: gate.label, pass: gatePass, commands: commandResults });
  }

  const summary = {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    pass: overallPass,
    gates: results,
  };
  const summaryPath = join(RUN_DIR, "summary.json");
  atomicWriteFile(summaryPath, `${JSON.stringify(summary, null, 2)}\n`, { mode: 0o600 });

  log("\n=== full acceptance chain summary ===");
  for (const gate of results) {
    log(`  [${gate.pass ? "PASS" : "FAIL"}] ${gate.label}`);
  }
  log(overallPass ? "\n✔ full acceptance chain PASSED" : "\n✖ full acceptance chain FAILED");

  return { pass: overallPass, results, summaryPath };
}

const isMainModule = process.argv[1] === new URL(import.meta.url).pathname;
if (isMainModule) {
  try {
    const result = await verifyFullAcceptanceChain();
    process.exit(result.pass ? 0 : 1);
  } catch (error) {
    logError(`full-acceptance-chain FAILED: ${error.message}`);
    process.exit(1);
  }
}
