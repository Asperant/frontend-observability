#!/usr/bin/env node
// Runs the full live acceptance gate chain (package.json §7 of the Stage 21
// spec) in a fixed, serial order.
//
// Isolation strategy: a full lab reset (`lab:purge && lab:init && lab:up &&
// lab:wait`) only actually creates OpenObserve streams lazily on first real
// ingest — `lab:streams:provision` alone SKIPS a stream that doesn't exist
// yet, so a bare purge+reprovision loop before every gate left dashboards
// and alerts unable to bind to real fields (live-verified: alert creation
// failed with CREATE_FAILED against a lab that had never actually ingested
// anything). The real desired-state establishment path is `test:streams`
// itself (it drives real browser ingestion, then provisions). So:
//   1. ONE full reset + full desired-state establishment
//      (streams/dashboards/alerts, via the same test:* commands used as
//      gates 1-2) runs once at the very start.
//   2. Gates that mutate shared RabbitMQ/queue/control state (and would
//      contaminate a sibling gate's queue-depth or admission assertions if
//      run back to back) get a *lightweight* reset — `lab:delivery:purge`
//      — instead of a full purge, which would also wipe the OpenObserve
//      dashboards/alerts/streams state the later recovery/backup gate
//      depends on for a real, non-empty backup source.
//   3. `test:recovery` uses its own fully disposable `frontend-observability-recovery-*`
//      compose projects and never touches `frontend-observability-lab`; no reset needed.
//
// Deliberately excludes the long-running real/soak durable-outage test
// (`lab:durable-outage-soak:evidence-only`) — that evidence is not
// regenerated by this chain; see the existing soak evidence file instead.
import { mkdirSync } from "node:fs";
import { join } from "node:path";
import { spawnSync } from "node:child_process";

import { atomicWriteFile, log, logError, repoRoot } from "./common.mjs";

// Deliberately NOT under .runtime/generated: `lab:purge` rm -rf's the entire
// .runtime/ tree — logs written there would be destroyed by a later reset.
// .artifacts/ is gitignored but untouched by lab:purge, so it survives the
// whole chain.
const RUN_DIR = join(repoRoot, ".artifacts", "full_acceptance_chain");

function runStep(cmd, args) {
  const result = spawnSync(cmd, args, { cwd: repoRoot, stdio: "inherit" });
  if (result.status !== 0) {
    throw new Error(`step "${cmd} ${args.join(" ")}" failed with status ${result.status}`);
  }
}

function fullResetAndEstablishDesiredState() {
  for (const [cmd, args] of [
    ["pnpm", ["run", "lab:purge", "--", "--yes"]],
    ["pnpm", ["run", "lab:init"]],
    ["pnpm", ["run", "lab:up"]],
    ["pnpm", ["run", "lab:wait"]],
  ]) {
    runStep(cmd, args);
  }
}

function queueOnlyReset() {
  runStep("pnpm", [
    "run",
    "lab:delivery:purge",
    "--",
    "--confirm",
    "PURGE-DURABLE-FRONTEND-TELEMETRY",
  ]);
}

